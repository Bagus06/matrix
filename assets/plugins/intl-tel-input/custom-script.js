$(document).ready(function() {
    /* =================== intl-tel-input =================== */
    const inputs = document.querySelectorAll('input[type="tel"]');
    const itiInstances = [];
    let isProgrammaticChange = false;

    function updatePlaceholder(input, iti) {
        let placeholder = input.getAttribute("placeholder") || "";
        placeholder = placeholder.replace(/^0/, "");
        input.setAttribute("placeholder", placeholder);
    }

    function updateTitle(input, iti) {
        const countryData = iti.getSelectedCountryData();
        const countryName = countryData.name; // e.g., India
        const dialCode = countryData.dialCode; // e.g., 91

        // Get placeholder generated by plugin
        let example = input.getAttribute("placeholder") || "";

        // Remove non-digit characters (spaces, dashes, etc.)
        example = example.replace(/\D/g, "");

        // Build international format without "+"
        const exampleNumber = dialCode + example;

        // Set dynamic title attribute
        input.setAttribute(
            "title",
            `Enter a valid ${countryName} phone number (e.g., ${exampleNumber})`
        );
    }

    inputs.forEach(function(input) {
        const iti = window.intlTelInput(input, {
            separateDialCode: false,
            formatOnDisplay: true,
            preferredCountries: ["in", "bd", "pk", "np"],
            utilsScript: BASE_URL + '/assets/plugins/intl-tel-input/utils.js'
        });

        itiInstances.push({
            input: input,
            iti: iti
        });

        input.itiInstance = iti;

        setTimeout(() => {
            updatePlaceholder(input, iti);
            updateTitle(input, iti);

            let value = input.value;

            if (value) {
                value = value.replace(/\D/g, "");

                isProgrammaticChange = true;
                iti.setNumber("+" + value);
                isProgrammaticChange = false;
            }
        }, 1000);

        input.addEventListener("countrychange", function() {
            if (!isProgrammaticChange) {
                input.value = "";
            }

            let value = input.value;

            if (value) {
                value = value.replace(/\D/g, "");

                // convert local → international
                if (value.startsWith("0")) {
                    const dialCode = iti.getSelectedCountryData().dialCode;
                    value = dialCode + value.substring(1);
                    input.value = value;
                }
            }

            updatePlaceholder(input, iti);
            updateTitle(input, iti);
        });

        input.addEventListener("input", function() {
            let value = input.value;
            value = value.replace(/\D/g, "");

            if (value.startsWith("0")) {
                const iti = input.itiInstance;
                if (!iti) return;
                const dialCode = iti.getSelectedCountryData().dialCode;
                value = dialCode + value.substring(1);
            }

            input.value = value;
        });
    });
    /* ====================================================== */
})